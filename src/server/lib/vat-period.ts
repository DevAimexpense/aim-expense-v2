// CTRL-13: เตือนเมื่อออกใบกำกับภาษีลงวันที่ในงวด ภ.พ.30 ที่เลยกำหนดยื่นแล้ว
//
// ภ.พ.30 ยื่นภายในวันที่ 15 ของเดือนถัดไป (ยื่นออนไลน์ได้ถึงวันที่ 23) — ออกใบกำกับย้อนหลังเข้างวดที่
// อาจยื่นไปแล้ว (เช่นออกแทนใบที่ยกเลิก ลงวันที่เดิม) ทำให้รายงานงวดนั้นเปลี่ยน → ต้องยื่นเพิ่มเติม
// ระบบไม่รู้ว่าลูกค้ายื่นแล้วหรือยัง จึงเตือนตั้งแต่พ้นวันที่ 15 (ไม่บล็อก — ออกแทนลงวันที่เดิมถูกต้องตามหลัก)
// ===========================================

const THAI_MONTHS = ["ม.ค.", "ก.พ.", "มี.ค.", "เม.ย.", "พ.ค.", "มิ.ย.", "ก.ค.", "ส.ค.", "ก.ย.", "ต.ค.", "พ.ย.", "ธ.ค."];

/** today / docDate = YYYY-MM-DD (เวลาไทย) · คืนข้อความเตือน หรือ undefined */
export function filedVatPeriodWarning(docDate: string, today: string): string | undefined {
  const d = /^(\d{4})-(\d{2})-(\d{2})/.exec(docDate || "");
  const t = /^(\d{4})-(\d{2})-(\d{2})/.exec(today || "");
  if (!d || !t) return undefined;
  const dy = Number(d[1]);
  const dm = Number(d[2]);
  // กำหนดยื่น = วันที่ 15 ของเดือนถัดจากเดือนของเอกสาร
  const dueY = dm === 12 ? dy + 1 : dy;
  const dueM = dm === 12 ? 1 : dm + 1;
  const due = `${dueY}-${String(dueM).padStart(2, "0")}-15`;
  if (today.slice(0, 10) <= due) return undefined;
  const period = `${THAI_MONTHS[dm - 1]} ${dy + 543}`;
  return `ใบกำกับภาษีลงวันที่อยู่ในงวด ภ.พ.30 เดือน ${period} ซึ่งเลยกำหนดยื่นแล้ว — ถ้ายื่นงวดนั้นไปแล้ว ต้องยื่นแบบเพิ่มเติม (ภาษีขายของงวดนั้นเปลี่ยน)`;
}
